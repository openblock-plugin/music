#!/usr/bin/env node
/**
 * Read every mp3 under ../assets/sounds/ and emit ../data/manifest.js
 * with base64-encoded byte data and a decoder that exposes
 * ArrayBuffer values keyed by relative path (e.g. 'drums/1-snare.mp3').
 *
 * The manifest.js produced is self-contained so that esbuild can inline it
 * into the final dist bundle without any custom loader configuration.
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const soundsDir = path.join(root, 'assets', 'sounds');
const outFile = path.join(root, 'data', 'manifest.js');

const walk = dir => {
    const out = [];
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            out.push(...walk(full));
        } else if (entry.isFile() && full.toLowerCase().endsWith('.mp3')) {
            out.push(full);
        }
    }
    return out;
};

const files = walk(soundsDir).sort();
console.log(`generate-manifest: found ${files.length} mp3 files`);

const entries = files.map(file => {
    const rel = path.relative(soundsDir, file).split(path.sep).join('/');
    const b64 = fs.readFileSync(file).toString('base64');
    return `    ${JSON.stringify(rel)}: ${JSON.stringify(b64)}`;
});

const header = `// AUTO-GENERATED by scripts/generate-manifest.js. Do not edit by hand.
// Run \`npm run gen-manifest\` to regenerate from assets/sounds/.
/* eslint-disable */

const _data = {
${entries.join(',\n')}
};

const _decode = b64 => {
    const bin = atob(b64);
    const len = bin.length;
    const bytes = new Uint8Array(len);
    for (let i = 0; i < len; i++) bytes[i] = bin.charCodeAt(i);
    return bytes.buffer;
};

const assetData = {};
for (const key in _data) {
    assetData[key] = _decode(_data[key]);
}

export default assetData;
`;

fs.mkdirSync(path.dirname(outFile), {recursive: true});
fs.writeFileSync(outFile, header);
const kb = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`generate-manifest: wrote ${outFile} (${kb} KB)`);
